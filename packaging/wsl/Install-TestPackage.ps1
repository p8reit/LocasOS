# LOCAS OS test appliance: run from the extracted GitHub Actions artifact folder.
[CmdletBinding()]
param(
    [string]$PackageDirectory = $PSScriptRoot
)
$ErrorActionPreference = "Stop"
$rootfs = Join-Path $PackageDirectory "locasos-wsl-amd64.tar"
$checksums = Join-Path $PackageDirectory "locasos-wsl-amd64.tar.sha256"
$importer = Join-Path $PackageDirectory "Install-LocasOS.ps1"
$buildInfoPath = Join-Path $PackageDirectory "locasos-build-info.json"
foreach ($file in @($rootfs, $checksums, $importer, $buildInfoPath)) {
    if (-not (Test-Path -LiteralPath $file -PathType Leaf)) { throw "Package is missing $file" }
}
$line = (Get-Content -LiteralPath $checksums -TotalCount 1)
if ($line -notmatch '^([0-9a-fA-F]{64})\s+\*?locasos-wsl-amd64\.tar\s*$') {
    throw "Invalid checksum manifest"
}
# CI-generated identity is a stale-package guard, not a publisher signature.
try {
    $build = Get-Content -LiteralPath $buildInfoPath -Raw | ConvertFrom-Json
} catch {
    throw "Invalid build metadata. Download the complete artifact from a successful WSL Appliance Build run."
}
if ($build.schema -ne 1 -or $build.repository -ne "p8reit/LocasOS" -or
    $build.commit -notmatch '^[a-fA-F0-9]{40}
if (-not $?) { throw "LOCAS installer failed" }
 -or
    $build.run_id -notmatch '^[0-9]+
if (-not $?) { throw "LOCAS installer failed" }
 -or
    $build.source_ref -notmatch '^refs/(heads/main|pull/[0-9]+/merge)
if (-not $?) { throw "LOCAS installer failed" }
) {
    throw "Unknown or outdated installation package. Use an artifact generated by the updated main workflow."
}
$installerSource = Get-Content -LiteralPath $importer -Raw
if (-not $installerSource.Contains("PASS: LOCAS services and Windows dashboard health verified.") -or
    -not $installerSource.Contains("http://127.0.0.1:59420/healthz")) {
    throw "Outdated installer lacks Windows dashboard readiness verification. Download a new package."
}
Write-Host "Installing LOCAS OS build $($build.commit) from $($build.source_ref)"
Write-Host "Build details: $($build.run_url)"
& $importer -RootfsArchive $rootfs -Sha256 $Matches[1]
if (-not $?) { throw "LOCAS installer failed" }
